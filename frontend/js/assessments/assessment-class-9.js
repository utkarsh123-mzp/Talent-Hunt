// ================= VARIABLES =================

let currentSubject = "Mathematics";

let currentQuestion = 0;

let userAnswers = [];


// ================= ELEMENTS =================

const subjectTabs =
    document.querySelectorAll(
        ".subject-tab"
    );

const subjectTitle =
    document.getElementById(
        "subjectTitle"
    );

const questionText =
    document.getElementById(
        "questionText"
    );

const optionsContainer =
    document.getElementById(
        "optionsContainer"
    );

const questionNumber =
    document.getElementById(
        "questionNumber"
    );

const questionCounter =
    document.getElementById(
        "questionCounter"
    );

const progressPercent =
    document.getElementById(
        "progressPercent"
    );

const progressFill =
    document.getElementById(
        "progressFill"
    );

const previousBtn =
    document.getElementById(
        "previousBtn"
    );

const nextBtn =
    document.getElementById(
        "nextBtn"
    );

const quizContainer =
    document.querySelector(
        ".quiz-container"
    );

const resultSection =
    document.getElementById(
        "resultSection"
    );

const resultSubject =
    document.getElementById(
        "resultSubject"
    );

const scoreText =
    document.getElementById(
        "scoreText"
    );

const percentageText =
    document.getElementById(
        "percentageText"
    );

const retryBtn =
    document.getElementById(
        "retryBtn"
    );

const backSubjectsBtn =
    document.getElementById(
        "backSubjectsBtn"
    );

const homeBtn =
    document.getElementById(
        "homeBtn"
    );


// ================= LOAD QUESTION =================

function loadQuestion() {

    const questions =
        assessments[currentSubject];

    const question =
        questions[currentQuestion];


    subjectTitle.textContent =
        currentSubject;


    questionText.textContent =
        question.question;


    questionNumber.textContent =
        String(currentQuestion + 1)
            .padStart(2, "0");


    questionCounter.textContent =
        `Question ${currentQuestion + 1} of ${questions.length}`;


    const percent =
        Math.round(
            ((currentQuestion + 1) /
                questions.length) * 100
        );


    progressPercent.textContent =
        `${percent}%`;


    progressFill.style.width =
        `${percent}%`;


    optionsContainer.innerHTML =
        "";


    const letters =
        ["A", "B", "C", "D"];


    question.options.forEach(
        (option, index) => {

            const button =
                document.createElement(
                    "button"
                );


            button.className =
                "option";


            if (
                userAnswers[currentQuestion] ===
                index
            ) {

                button.classList.add(
                    "selected"
                );

            }


            button.innerHTML = `

                <span class="option-letter">
                    ${letters[index]}
                </span>

                <span>
                    ${option}
                </span>

            `;


            button.addEventListener(
                "click",
                () => {

                    selectAnswer(index);

                }
            );


            optionsContainer.appendChild(
                button
            );

        }
    );


    previousBtn.disabled =
        currentQuestion === 0;


    if (
        currentQuestion ===
        questions.length - 1
    ) {

        nextBtn.innerHTML = `
            Submit
            <i class="ph ph-check"></i>
        `;

    } else {

        nextBtn.innerHTML = `
            Next
            <i class="ph ph-arrow-right"></i>
        `;

    }

}


// ================= SELECT ANSWER =================

function selectAnswer(index) {

    userAnswers[currentQuestion] =
        index;


    document
        .querySelectorAll(".option")
        .forEach(
            option => {

                option.classList.remove(
                    "selected"
                );

            }
        );


    document
        .querySelectorAll(".option")
        [index]
        .classList.add("selected");

}


// ================= NEXT =================

nextBtn.addEventListener(
    "click",
    () => {

        const questions =
            assessments[currentSubject];


        if (
            userAnswers[currentQuestion] ===
            undefined
        ) {

            alert(
                "Please select an answer first."
            );

            return;

        }


        if (
            currentQuestion <
            questions.length - 1
        ) {

            currentQuestion++;

            loadQuestion();

        } else {

            showResult();

        }

    }
);


// ================= PREVIOUS =================

previousBtn.addEventListener(
    "click",
    () => {

        if (currentQuestion > 0) {

            currentQuestion--;

            loadQuestion();

        }

    }
);


// ================= SUBJECT CHANGE =================

subjectTabs.forEach(tab => {

    tab.addEventListener(
        "click",
        () => {

            subjectTabs.forEach(
                item => {

                    item.classList.remove(
                        "active"
                    );

                }
            );


            tab.classList.add(
                "active"
            );


            currentSubject =
                tab.dataset.subject;


            currentQuestion = 0;

            userAnswers = [];


            resultSection.classList.add(
                "hidden"
            );

            quizContainer.classList.remove(
                "hidden"
            );


            loadQuestion();

        }
    );

});


// ================= RESULT =================

function showResult() {

    const questions =
        assessments[currentSubject];


    let score = 0;


    questions.forEach(
        (question, index) => {

            if (
                userAnswers[index] ===
                question.answer
            ) {

                score++;

            }

        }
    );


    const percentage =
        Math.round(
            (score / questions.length) * 100
        );


    resultSubject.textContent =
        currentSubject;


    scoreText.textContent =
        `${score} / ${questions.length}`;


    percentageText.textContent =
        `${percentage}%`;


    quizContainer.classList.add(
        "hidden"
    );


    resultSection.classList.remove(
        "hidden"
    );


    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}


// ================= RETRY =================

retryBtn.addEventListener(
    "click",
    () => {

        currentQuestion = 0;

        userAnswers = [];


        resultSection.classList.add(
            "hidden"
        );


        quizContainer.classList.remove(
            "hidden"
        );


        loadQuestion();

    }
);


// ================= BACK TO SUBJECTS =================

backSubjectsBtn.addEventListener(
    "click",
    () => {

        resultSection.classList.add(
            "hidden"
        );


        quizContainer.classList.remove(
            "hidden"
        );


        document
            .querySelector(
                ".subject-selector"
            )
            .scrollIntoView({
                behavior: "smooth"
            });

    }
);


// ================= HOME =================

homeBtn.addEventListener(
    "click",
    () => {

        window.location.href =
            "../school-students/class-9.html";

    }
);


// ================= INITIAL LOAD =================

loadQuestion();