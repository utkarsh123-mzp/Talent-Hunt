// ================= TOTAL QUESTION COUNT =================

function calculateTotalQuestions() {

    let total = 0;


    Object.values(
        assessments
    ).forEach(
        subject => {

            total += subject.length;

        }
    );


    questionCount.textContent =
        total;

}


