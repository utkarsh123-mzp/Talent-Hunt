// ================= INITIALIZE =================

function initializeAssessment() {

    userAnswers = {};

    currentQuestionIndex = 0;

    loadQuestion();

}


initializeAssessment();


// ================= LOAD QUESTION =================

function loadQuestion() {

    const questions =
        assessments[currentSubject];

    const question =
        questions[currentQuestionIndex];


    totalQuestions.textContent =
        questions.length;


    currentQuestion.textContent =
        currentQuestionIndex + 1;


    questionNumber.textContent =
        `QUESTION ${String(
            currentQuestionIndex + 1
        ).padStart(2, "0")}`;


    questionText.textContent =
        question.question;


    optionsContainer.innerHTML = "";


    const letters =
        ["A", "B", "C", "D"];


    question.options.forEach(
        (option, index) => {

            const button =
                document.createElement(
                    "button"
                );


            button.className =
                "option";


            button.innerHTML = `

                <span class="option-letter">
                    ${letters[index]}
                </span>

                <span>
                    ${option}
                </span>

            `;


            if (
                userAnswers[
                    currentQuestionIndex
                ] === index
            ) {

                button.classList.add(
                    "selected"
                );

            }


            button.addEventListener(
                "click",
                () => {

                    selectAnswer(index);

                }
            );


            optionsContainer.appendChild(
                button
            );

        }
    );


    updateProgress();


    previousBtn.disabled =
        currentQuestionIndex === 0;


    if (
        currentQuestionIndex ===
        questions.length - 1
    ) {

        nextBtn.innerHTML = `
            Submit Assessment
            <i class="ph ph-check"></i>
        `;

    } else {

        nextBtn.innerHTML = `
            Next
            <i class="ph ph-arrow-right"></i>
        `;

    }

}


// ================= SELECT ANSWER =================

function selectAnswer(index) {

    userAnswers[
        currentQuestionIndex
    ] = index;


    const options =
        document.querySelectorAll(
            ".option"
        );


    options.forEach(
        option => {

            option.classList.remove(
                "selected"
            );

        }
    );


    options[index].classList.add(
        "selected"
    );

}


// ================= NEXT =================

nextBtn.addEventListener(
    "click",
    () => {

        const questions =
            assessments[currentSubject];


        if (
            currentQuestionIndex ===
            questions.length - 1
        ) {

            finishAssessment();

            return;

        }


        currentQuestionIndex++;

        loadQuestion();

    }
);


// ================= PREVIOUS =================

previousBtn.addEventListener(
    "click",
    () => {

        if (
            currentQuestionIndex > 0
        ) {

            currentQuestionIndex--;

            loadQuestion();

        }

    }
);


// ================= PROGRESS =================

function updateProgress() {

    const total =
        assessments[currentSubject].length;


    const progress =
        (
            (currentQuestionIndex + 1)
            / total
        ) * 100;


    progressBar.style.width =
        `${progress}%`;

}


// ================= SUBJECT SWITCH =================

subjectTabs.forEach(tab => {

    tab.addEventListener(
        "click",
        () => {

            subjectTabs.forEach(
                item => {

                    item.classList.remove(
                        "active"
                    );

                }
            );


            tab.classList.add(
                "active"
            );


            currentSubject =
                tab.dataset.subject;


            currentQuestionIndex = 0;

            userAnswers = {};


            updateSubjectInformation();

            loadQuestion();

        }
    );

});


// ================= SUBJECT INFORMATION =================

function updateSubjectInformation() {

    const names = {

        mathematics:
            "Mathematics",

        science:
            "Science",

        english:
            "English",

        hindi:
            "Hindi",

        social:
            "Social Science",

        computer:
            "Computer"

    };


    const name =
        names[currentSubject];


    subjectLabel.textContent =
        name.toUpperCase();


    subjectTitle.textContent =
        `${name} Assessment`;

}


// ================= RESULT =================

function finishAssessment() {

    const questions =
        assessments[currentSubject];


    let score = 0;


    questions.forEach(
        (question, index) => {

            if (
                userAnswers[index] ===
                question.answer
            ) {

                score++;

            }

        }
    );


    scoreElement.textContent =
        score;


    const names = {

        mathematics:
            "Mathematics",

        science:
            "Science",

        english:
            "English",

        hindi:
            "Hindi",

        social:
            "Social Science",

        computer:
            "Computer"

    };


    resultSubject.textContent =
        `${names[currentSubject]} Assessment`;


    let message;


    const percentage =
        (score / questions.length) * 100;


    if (percentage >= 80) {

        message =
            "Excellent! Your board preparation is strong.";

    } else if (percentage >= 60) {

        message =
            "Good work! A little more practice will make you stronger.";

    } else if (percentage >= 40) {

        message =
            "Keep practicing. Focus on your weak concepts.";

    } else {

        message =
            "Don't give up! Revise the concepts and try again.";

    }


    resultMessage.textContent =
        message;


    resultOverlay.classList.add(
        "show"
    );

}


