    document.getElementById(
        "submitBtn"
    );


// ================= SUBJECT SELECTION =================

const subjectButtons =
    document.querySelectorAll(
        ".subject-btn"
    );


subjectButtons.forEach(button => {

    button.addEventListener(
        "click",
        () => {

            selectedSubject =
                button.dataset.subject;

            startAssessment();

        }
    );

});


// ================= START ASSESSMENT =================

function startAssessment() {

    currentQuestionIndex = 0;

    userAnswers =
        new Array(
            assessmentData[selectedSubject].length
        ).fill(null);


    subjectSelection.classList.add(
        "hidden"
    );


    document.getElementById(
        "introSection"
    ).classList.add(
        "hidden"
    );


    resultSection.classList.add(
        "hidden"
    );


    quizSection.classList.remove(
        "hidden"
    );


    quizSubject.textContent =
        selectedSubject;


    totalQuestions.textContent =
        assessmentData[
            selectedSubject
        ].length;


    loadQuestion();

}


// ================= LOAD QUESTION =================

function loadQuestion() {

    const questions =
        assessmentData[
            selectedSubject
        ];


    const question =
        questions[
            currentQuestionIndex
        ];


    currentQuestion.textContent =
        currentQuestionIndex + 1;


    questionNumber.textContent =
        `Question ${currentQuestionIndex + 1}`;


    questionText.textContent =
        question.question;


    optionsContainer.innerHTML = "";


    const letters =
        ["A", "B", "C", "D"];


    question.options.forEach(
        (option, index) => {

            const optionButton =
                document.createElement(
                    "button"
                );


            optionButton.className =
                "option";


            if (
                userAnswers[
                    currentQuestionIndex
                ] === index
            ) {

                optionButton.classList.add(
                    "selected"
                );

            }


            optionButton.innerHTML = `

                <span class="option-letter">
                    ${letters[index]}
                </span>

                <span>
                    ${option}
                </span>

            `;


            optionButton.addEventListener(
                "click",
                () => {

                    selectAnswer(index);

                }
            );


            optionsContainer.appendChild(
                optionButton
            );

        }
    );


    updateProgress();

    updateButtons();

}


// ================= SELECT ANSWER =================

function selectAnswer(index) {

    userAnswers[
        currentQuestionIndex
    ] = index;


    const options =
        document.querySelectorAll(
            ".option"
        );


    options.forEach(
        option => {

            option.classList.remove(
                "selected"
            );

        }
    );


    if (options[index]) {

        options[index].classList.add(
            "selected"
        );

    }

}


// ================= PROGRESS =================

function updateProgress() {

    const total =
        assessmentData[
            selectedSubject
        ].length;


    const progress =
        (
            (currentQuestionIndex + 1)
            / total
        ) * 100;


    progressBar.style.width =
        `${progress}%`;

}


// ================= BUTTONS =================

function updateButtons() {

    if (currentQuestionIndex === 0) {

        previousBtn.style.visibility =
            "hidden";

    } else {

        previousBtn.style.visibility =
            "visible";

    }


    const total =
        assessmentData[
            selectedSubject
        ].length;


    if (
        currentQuestionIndex ===
        total - 1
    ) {

        nextBtn.classList.add(
            "hidden"
        );

        submitBtn.classList.remove(
            "hidden"
        );

    } else {

        nextBtn.classList.remove(
            "hidden"
        );

        submitBtn.classList.add(
            "hidden"
        );

    }

}


// ================= NEXT =================

nextBtn.addEventListener(
    "click",
    () => {

        if (
            userAnswers[
                currentQuestionIndex
            ] === null
        ) {

            alert(
                "Please select an answer before continuing."
            );

            return;

        }


        currentQuestionIndex++;

        loadQuestion();

        window.scrollTo({
            top: 0,
            behavior: "smooth"
        });

    }
);


// ================= PREVIOUS =================

previousBtn.addEventListener(
    "click",
    () => {

        if (currentQuestionIndex > 0) {

            currentQuestionIndex--;

            loadQuestion();

        }

    }
);


// ================= SUBMIT =================

submitBtn.addEventListener(
    "click",
    () => {

        const unanswered =
            userAnswers.filter(
                answer => answer === null
            ).length;


        if (unanswered > 0) {

            const confirmSubmit =
                confirm(
                    `You have ${unanswered} unanswered question(s). Do you still want to submit?`
                );


            if (!confirmSubmit) {

                return;

            }

        }


        calculateResult();

    }
);


// ================= RESULT =================

function calculateResult() {

    const questions =
        assessmentData[
            selectedSubject
        ];


    let correct = 0;


    questions.forEach(
        (question, index) => {

            if (
                userAnswers[index] ===
                question.answer
            ) {

                correct++;

            }

        }
    );


    const total =
        questions.length;


    const wrong =
        total - correct;


    const percentage =
        Math.round(
            (correct / total) * 100
        );


    document.getElementById(
        "score"
    ).textContent =
        `${percentage}%`;


    document.getElementById(
        "correctAnswers"
    ).textContent =
        correct;


    document.getElementById(
        "wrongAnswers"
    ).textContent =
        wrong;


    document.getElementById(
        "totalAnswered"
    ).textContent =
        total;


    let message;


    if (percentage >= 80) {

        message =
            "Excellent performance! Keep learning and challenging yourself.";

    } else if (percentage >= 60) {

        message =
            "Good job! Your concepts are developing well.";

    } else if (percentage >= 40) {

        message =
            "Nice attempt! Revise the concepts and try again.";

    } else {

        message =
            "Keep practising. Every attempt helps you improve.";

    }


    document.getElementById(
        "resultMessage"
    ).textContent =
        message;


    quizSection.classList.add(
        "hidden"
    );


    resultSection.classList.remove(
        "hidden"
    );


    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}


