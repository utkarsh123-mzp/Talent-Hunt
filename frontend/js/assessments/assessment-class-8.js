// ================= VARIABLES =================

let selectedSubject = "";

let currentQuestionIndex = 0;

let userAnswers = [];


// ================= ELEMENTS =================

const subjectSelection =
    document.getElementById(
        "subjectSelection"
    );

const quizSection =
    document.getElementById(
        "quizSection"
    );

const resultSection =
    document.getElementById(
        "resultSection"
    );

